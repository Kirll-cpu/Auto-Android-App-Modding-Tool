#!/usr/bin/env python3
"""Index every SKILL.md under a provisioned skills directory.

Usage: python3 tools/skills_registry.py [SKILLS_DIR] (default: ~/skills)
The index reports files, not whether their tools/dependencies are runnable.
"""
import os
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote


def frontmatter(path):
    """Extract a best-effort name and description without executing content."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")[:16000].replace("\r\n", "\n")
    except OSError:
        return None, ""
    match = re.match(r"^---\s*\n(.*?)\n---(?:\s*\n|\s*$)", text, re.S)
    if not match:
        return None, ""
    lines = match.group(1).splitlines()
    name, desc = None, ""
    for i, line in enumerate(lines):
        if line.startswith("name:"):
            name = line.split(":", 1)[1].strip().strip('"\'') or None
        elif line.startswith("description:"):
            desc = line.split(":", 1)[1].strip()
            if desc in (">", "|", ">-", "|-", ""):
                parts = []
                for nxt in lines[i + 1:]:
                    if nxt.startswith((" ", "\t")):
                        parts.append(nxt.strip())
                    elif nxt.strip():
                        break
                desc = " ".join(parts)
    return name, re.sub(r"\s+", " ", desc).strip().strip('"\'')


def build(skills_dir):
    root = Path(skills_dir)
    if not root.is_dir():
        raise ValueError(f"Skills directory does not exist: {root}")
    groups = defaultdict(list)
    for directory, dirs, files in os.walk(root, followlinks=False):
        dirs[:] = sorted(d for d in dirs if d != ".git" and not (Path(directory) / d).is_symlink())
        if "SKILL.md" not in files:
            continue
        path = Path(directory) / "SKILL.md"
        if path.is_symlink():
            continue
        rel = path.relative_to(root)
        parts = rel.parts
        group = f"community/{parts[1]}" if len(parts) > 2 and parts[0] == "community" else parts[0]
        name, desc = frontmatter(path)
        groups[group].append((name or rel.parent.name, desc, rel, not bool(name)))

    out = ["# 🧰 Installed Skills Registry", "", "Auto-generated by `tools/skills_registry.py` — do not edit by hand.",
           f"Skills root: `{root}`", "", "This indexes source files only; dependencies and runtime readiness are not verified.",
           "Entries without a frontmatter name are marked for manual review.", ""]
    total = 0
    for group, entries in sorted(groups.items()):
        out += [f"## {group} — {len(entries)} files", "", "| Skill | Description |", "|---|---|"]
        for name, desc, rel, missing in sorted(entries, key=lambda item: str(item[2])):
            label = name.replace("|", "\\|").replace("[", "\\[").replace("]", "\\]").replace("`", "'")
            link = quote(rel.as_posix(), safe="/")
            description = (desc[:160] or ("No frontmatter name; review manually" if missing else "No description"))
            out.append(f"| [`{label}`]({link}) | {description.replace('|', '/')} |")
        out.append("")
        total += len(entries)
    out.append(f"**Total: {total} SKILL.md files**")
    dest = root / "SKILLS-REGISTRY.md"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"registry: {total} SKILL.md files -> {dest}")
    return total


if __name__ == "__main__":
    try:
        build(sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/skills"))
    except (OSError, ValueError) as error:
        print(f"registry error: {error}", file=sys.stderr)
        sys.exit(1)
